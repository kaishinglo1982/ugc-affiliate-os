/** The single-user system treats the signed-in user as owner. */
export function roleForUser(_user: { id: string; email: string }): Role {
  return "owner";
}

export function permissionsForRole(role: Role): Set<Permission> {
  return new Set(ROLE_PERMISSIONS[role]);
}

export function hasPermission(user: { id: string; email: string } | null, permission: Permission): boolean {
  if (!user) return false;
  return permissionsForRole(roleForUser(user)).has(permission);
}
